/**
 * Generate TypeScript declarations for the flat colour-theme map so editors give
 * autocomplete and dev-time checking on keys (mirrors gen-l10n-types.js for l10n).
 * Reads the flat colours.json and emits cypress/support/colours.d.ts typing the
 * global `colours` as Record<ColourKey, string> — so `colours['<caret>']`
 * autocompletes every key and a typo'd/removed key is a type error.
 * Re-run when keys change.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const flat = JSON.parse(fs.readFileSync(path.join(ROOT, 'cypress/colours/colours.json'), 'utf8'));

const keys = Object.keys(flat).sort((a, b) => a.localeCompare(b));

const union = (arr) => arr.map((k) => `  | '${k}'`).join('\n');
const out = `// AUTO-GENERATED by scripts/gen-colours-types.js — do not edit by hand.
// Regenerate after changing colour keys: node scripts/gen-colours-types.js

type ColourKey =
${union(keys)};

/** Flat colour-theme map: every dot-namespaced key resolves to the active-theme colour value. */
declare const colours: Record<ColourKey, string>;
`;

fs.writeFileSync(path.join(ROOT, 'cypress/support/colours.d.ts'), out);
console.log(`Wrote cypress/support/colours.d.ts: ${keys.length} keys.`);
