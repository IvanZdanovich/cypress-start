// Skip if explicitly disabled
if (process.env.SKIP_HOOKS === 'true') {
  console.log('SKIP_HOOKS=true detected. Skipping git hooks setup.');
  process.exit(0);
}

// Skip in CI environments automatically
if (process.env.CI || process.env.GITHUB_ACTIONS || process.env.GITLAB_CI || process.env.CIRCLECI || process.env.JENKINS_HOME || process.env.TRAVIS) {
  console.log('CI environment detected. Skipping git hooks setup.');
  process.exit(0);
}

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const { gitExecutable, sanitizedEnv } = require('./git-exec-lib');

const repoDir = path.join(__dirname, '..');

/**
 * Run a git command in the repo and return trimmed stdout, or null on failure.
 * @param {string[]} args
 * @returns {string|null}
 */
function git(args) {
  const result = spawnSync(gitExecutable, args, { encoding: 'utf8', cwd: repoDir, env: sanitizedEnv });
  if (result.error || result.status !== 0) return null;
  return result.stdout.trim();
}

/**
 * Hook installation must never break `npm install` / `npm ci` for anyone, so
 * every failure is reported as a warning and the script exits 0.
 * @param {string} message
 */
function warnAndExit(message) {
  console.warn(`WARN ${message}`);
  console.warn('     The pre-commit check will NOT run. Run `npm run hooks:setup` after fixing the cause.');
  process.exit(0);
}

// Works for regular clones, worktrees and submodules (where `.git` is a file).
const gitCommonDir = git(['rev-parse', '--path-format=absolute', '--git-common-dir']);
if (!gitCommonDir) {
  console.log('Not inside a git repository (or git is unavailable). Skipping git hooks setup.');
  process.exit(0);
}

const hooksDir = path.join(gitCommonDir, 'hooks');
const preCommitHook = path.join(hooksDir, 'pre-commit');

// Node used for `npm install` — embedded as a fallback for GUI git clients
// (IntelliJ/WebStorm, SourceTree, GitHub Desktop, Fork) that do not load the
// shell profile and therefore have no nvm/volta/fnm node on PATH.
// Forward slashes keep the path safe inside /bin/sh on Windows (Git Bash).
const installNodePath = process.execPath.split(path.sep).join('/');

// The hook resolves everything at runtime (repo root, git dir, node), so it
// keeps working after the repo is moved/renamed and inside every worktree.
const hookContent = `#!/bin/sh
# Pre-commit hook - Code quality check
# Auto-generated by scripts/setup-git-hooks.js (npm postinstall / npm run hooks:setup)

# Skip hook during merge or rebase (git-path resolves correctly in worktrees)
for marker in MERGE_HEAD rebase-merge rebase-apply; do
  if [ -e "$(git rev-parse --git-path "$marker")" ]; then
    echo "Merge/rebase in progress. Skipping ESLint check."
    exit 0
  fi
done

REPO_ROOT="$(git rev-parse --show-toplevel)"
CHECK_SCRIPT="$REPO_ROOT/scripts/pre-commit-lint.js"

if [ ! -f "$CHECK_SCRIPT" ]; then
  echo "Pre-commit script not found at $CHECK_SCRIPT. Skipping ESLint check."
  exit 0
fi

# Resolve node: PATH first, then common install locations used by GUI clients.
NODE_BIN="$(command -v node 2>/dev/null)"
if [ -z "$NODE_BIN" ]; then
  export NVM_DIR="\${NVM_DIR:-$HOME/.nvm}"
  if [ -s "$NVM_DIR/nvm.sh" ]; then
    . "$NVM_DIR/nvm.sh" >/dev/null 2>&1
    NODE_BIN="$(command -v node 2>/dev/null)"
  fi
fi
if [ -z "$NODE_BIN" ]; then
  for candidate in \\
    "${installNodePath}" \\
    "$HOME/.volta/bin/node" \\
    "$HOME/.local/share/fnm/aliases/default/bin/node" \\
    "$HOME/.fnm/aliases/default/bin/node" \\
    "/opt/homebrew/bin/node" \\
    "/usr/local/bin/node" \\
    "/usr/bin/node" \\
    "/c/Program Files/nodejs/node.exe"; do
    if [ -x "$candidate" ]; then
      NODE_BIN="$candidate"
      break
    fi
  done
fi
if [ -z "$NODE_BIN" ]; then
  echo "FAIL Node.js not found for the pre-commit hook."
  echo "     Ensure 'node' is on PATH for your git client, then re-run: npm run hooks:setup"
  echo "     Emergency bypass (fix afterward): git commit --no-verify -m \\"your message\\""
  exit 1
fi

# Make the resolved node's directory available to child processes.
PATH="$(dirname "$NODE_BIN"):$PATH"
export PATH

echo "Running ESLint check..."
cd "$REPO_ROOT" || exit 1
exec "$NODE_BIN" "$CHECK_SCRIPT"
`;

// Owner-only rwx: git runs the hook as the committing user, so group/others
// need no access (prevents other local users from reading or tampering with it).
const HOOK_MODE = 0o700;

try {
  fs.mkdirSync(hooksDir, { recursive: true });
  fs.writeFileSync(preCommitHook, hookContent, { mode: HOOK_MODE });
  // writeFileSync's mode is ignored when the file already exists.
  fs.chmodSync(preCommitHook, HOOK_MODE);
} catch (error) {
  warnAndExit(`Failed to install pre-commit hook: ${error.message}`);
}

console.log(`Pre-commit hook installed: ${preCommitHook}`);

// A configured core.hooksPath (often set globally by husky or corporate tooling)
// makes git ignore .git/hooks entirely, silently disabling the check.
const hooksPath = git(['config', '--get', 'core.hooksPath']);
if (hooksPath) {
  const effectiveHooksDir = git(['rev-parse', '--path-format=absolute', '--git-path', 'hooks']);
  if (effectiveHooksDir && path.resolve(effectiveHooksDir) !== path.resolve(hooksDir)) {
    console.warn(`WARN core.hooksPath is set to "${hooksPath}" — git will NOT run the pre-commit check.`);
    console.warn('     Fix for this repo only:');
    console.warn(`       git config --local core.hooksPath "${hooksDir.split(path.sep).join('/')}"`);
  }
}
