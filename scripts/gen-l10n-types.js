/**
 * Generate TypeScript declarations for the flat localization map so editors give
 * autocomplete and dev-time checking on keys (transloco "typed translations" style).
 * Reads the flat l10n.json and emits cypress/support/l10n.d.ts typing the global
 * `l10n` as Record<L10nKey, string> — so `l10n['<caret>']` autocompletes every key
 * inside the quotes and a typo'd/removed key is a type error. Re-run when keys change.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const flat = JSON.parse(fs.readFileSync(path.join(ROOT, 'cypress/localization/l10n.json'), 'utf8'));

const keys = Object.keys(flat).sort((a, b) => a.localeCompare(b));

const union = (arr) => arr.map((k) => `  | '${k}'`).join('\n');
const out = `// AUTO-GENERATED by scripts/gen-l10n-types.js — do not edit by hand.
// Regenerate after changing localization keys: node scripts/gen-l10n-types.js

type L10nKey =
${union(keys)};

/** Flat localization map: every dot-namespaced key resolves to the active-language string. */
declare const l10n: Record<L10nKey, string>;
`;

fs.writeFileSync(path.join(ROOT, 'cypress/support/l10n.d.ts'), out);
console.log(`Wrote cypress/support/l10n.d.ts: ${keys.length} keys.`);
